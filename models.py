import torch
import torch.nn as nn
import torch.nn.functional as F

class NeuralNet2(nn.Module):
  def __init__(self):
    super().__init__()
    self.conv1 = nn.Conv2d(3, 16, 5, padding=2)
    self.conv2 = nn.Conv2d(16, 32, 5, padding=2)
    self.conv3 = nn.Conv2d(32, 64, 3, padding=1)
    self.conv4 = nn.Conv2d(64, 128, 3, padding=1)
    self.pool = nn.MaxPool2d(2, 2)
    self.embedding = nn.Linear(8192, 256)
    self.fc1 = nn.Linear(256, 128)
    self.bn1 = nn.BatchNorm1d(128)
    self.fc2 = nn.Linear(128, 64)
    self.bn2 = nn.BatchNorm1d(64)
    self.fc3 = nn.Linear(64, 1)
    self.dropout = nn.Dropout(0.4)
  def forward_once(self, x):
    x = self.pool(F.relu(self.conv1(x)))
    x = self.pool(F.relu(self.conv2(x)))
    x = self.pool(F.relu(self.conv3(x)))
    x = self.pool(F.relu(self.conv4(x)))
    x = x.flatten(1)
    x = self.embedding(x)
    return F.normalize(x, p=2, dim=1)
  def forward(self, x1, x2):
    x1 = self.forward_once(x1)
    x2 = self.forward_once(x2)
    x = torch.abs(x1 - x2)
    x = F.relu(self.bn1(self.fc1(x)))
    x = self.dropout(x)
    x = F.relu(self.bn2(self.fc2(x)))
    x = self.dropout(x)
    x = self.fc3(x)
    return x
  
class NeuralNet3(nn.Module):
  def __init__(self):
    super().__init__()
    self.conv1 = nn.Conv2d(3, 16, 5, padding=2)
    self.conv2 = nn.Conv2d(16, 32, 5, padding=2)
    self.conv3 = nn.Conv2d(32, 64, 3, padding=1)
    self.conv4 = nn.Conv2d(64, 128, 3, padding=1)
    self.pool = nn.MaxPool2d(2, 2)
    self.embedding = nn.Linear(8192, 256)
    self.fc1 = nn.Linear(512, 128)
    self.bn1 = nn.BatchNorm1d(128)
    self.fc2 = nn.Linear(128, 64)
    self.bn2 = nn.BatchNorm1d(64)
    self.fc3 = nn.Linear(64, 1)
    self.dropout = nn.Dropout(0.4)
  def forward_once(self, x):
    x = self.pool(F.relu(self.conv1(x)))
    x = self.pool(F.relu(self.conv2(x)))
    x = self.pool(F.relu(self.conv3(x)))
    x = self.pool(F.relu(self.conv4(x)))
    x = x.flatten(1)
    x = self.embedding(x)
    return F.normalize(x, p=2, dim=1)
  def forward(self, x1, x2, x3):
    x1 = self.forward_once(x1)
    x2 = self.forward_once(x2)
    x3 = self.forward_once(x3)
    diff1 = torch.abs(x1 - x3)
    diff2 = torch.abs(x2 - x3)
    mag1 = torch.sum(diff1 ** 2, dim=1, keepdim=True)
    mag2 = torch.sum(diff2 ** 2, dim=1, keepdim=True)
    mini = torch.where(mag1 < mag2, diff1, diff2)
    maxi = torch.where(mag1 < mag2, diff2, diff1)
    x = torch.cat((mini, maxi), dim=1)
    x = F.relu(self.bn1(self.fc1(x)))
    x = self.dropout(x)
    x = F.relu(self.bn2(self.fc2(x)))
    x = self.dropout(x)
    x = self.fc3(x)
    return x

